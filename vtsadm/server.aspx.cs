        protected void GridView2_RowCommand(object sender, System.Web.UI.WebControls.GridViewCommandEventArgs e)
        {
            try
            {
                div_comment.InnerHtml = "";
                Int32 iRow = Convert.ToInt32(e.CommandArgument);
               string sServerID = ""; string sServerName = ""; string sDescr = ""; string sStatus = "";
                sServerID = (e.CommandSource as GridView).Rows[iRow].Cells[0].Text.Trim();
                sServerName = (e.CommandSource as GridView).Rows[iRow].Cells[1].Text.Trim();
                sDescr = (e.CommandSource as GridView).Rows[iRow].Cells[2].Text.Trim();
                sStatus = (e.CommandSource as GridView).Rows[iRow].Cells[3].Text.Trim();
                switch (e.CommandName.ToUpper())
                {
                    case "CHANGES":
                        if (sStatus == "RG")
                        {
                            txtServerID.Text = sServerID;
                            txtServerName.Text = sServerName;
                            txtDescr.Text = sDescr;
                            txtServerID.Attributes.Add("disabled", "disabled");
                            CmdSubmit.Text = "Update";
                            div_comment.InnerHtml = "";
                        }
                        else
                        {
                            div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Server can not be edited due to status have been changed into " + sStatus + "</div>";
                        }
                        break;
                    default:
                        break;
                }

            }
            catch (Exception ex)
            {
                div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Removing server has been failed!! (" + ex.Message + ")</div>";
            }
        }

