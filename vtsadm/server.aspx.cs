                {
                    if (txtServerID.Text.Trim() != "")
                    {
                        strSQL = "sp_update_server '" + txtServerID.Text.Trim() + "','" + txtServerName.Text.Trim() + "','" + txtDescr.Text.Trim() + "','" + Session["ClsTypeUserID"].ToString() + "'";
                        if (ec.Execute(strSQL, Session["ClsTypeDBConnStringSQL"].ToString().Trim(), ref intAff))
                        {
                            if (intAff > 0)
                            {
                                clear();
                                Open_GridView();
                                div_comment.InnerHtml = "<div class='alert alert-success' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Success!</strong> Server has been update successfully!</div>";
