        protected void GridView2_RowCommand(object sender, System.Web.UI.WebControls.GridViewCommandEventArgs e)
        {
            try
            {
                Int32 iRow = Convert.ToInt32(e.CommandArgument);
                string sVendorID = ""; string sVendorName = ""; string sAddress = ""; string sStatus = ""; 
                sVendorID = (e.CommandSource as GridView).Rows[iRow].Cells[0].Text.Trim();
                sVendorName = (e.CommandSource as GridView).Rows[iRow].Cells[1].Text.Trim();
                sAddress = (e.CommandSource as GridView).Rows[iRow].Cells[2].Text.Trim();
                sStatus = (e.CommandSource as GridView).Rows[iRow].Cells[3].Text.Trim();
                switch (e.CommandName.ToUpper())
                {
                    case "CHANGES":
                        if (sStatus.ToUpper().Trim() == "RG")
                        {
                            txtVendorID.Text = sVendorID;
                            txtVendorName.Text = sVendorName;
                            txtAddress.Value = sAddress;
                            txtVendorID.Attributes.Add("disabled", "disabled");
                            CmdSubmit.Text = "Update";
                            div_comment.InnerHtml = "";
                        }
                        else
                        {
                            div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Vendor can not be edited, due to status code has been " + sStatus + "</div>";
                        }
                        break;
                    default:
                        break;
                }

            }
            catch (Exception ex)
            {

            }
        }

