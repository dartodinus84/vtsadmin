        protected void GridView2_RowCommand(object sender, System.Web.UI.WebControls.GridViewCommandEventArgs e)
        {
            try
            {
                Int32 iRow = Convert.ToInt32(e.CommandArgument);
                String strSQL = ""; ExecCommand ec = new ExecCommand();
                Int32 intAff = 0;
                string sVehicleTypeID = "";
                string sVehicleBrandID = "";
                string sBrandVehicle = "";
                String sTypeVehicle = "";
                string sStatus = "";
                string sErr = "";

                sVehicleTypeID = (e.CommandSource as GridView).Rows[iRow].Cells[0].Text.Trim();
                sVehicleBrandID = (e.CommandSource as GridView).Rows[iRow].Cells[1].Text.Trim();
                sBrandVehicle = (e.CommandSource as GridView).Rows[iRow].Cells[2].Text.Trim();
                sTypeVehicle = (e.CommandSource as GridView).Rows[iRow].Cells[3].Text.Trim();
                sStatus = (e.CommandSource as GridView).Rows[iRow].Cells[4].Text.Trim();

                switch (e.CommandName.ToUpper())
                {
                    case "CHANGES":
                        if (sStatus.ToUpper().Trim() == "RG")
                        {
                            txtVehicleTypeID.Text = sVehicleTypeID;
                            CmbVehicleBrandID.SelectedValue= sVehicleBrandID;
                            txtTypeVehicle.Text = sTypeVehicle;
                            txtVehicleTypeID.Attributes.Add("disabled", "disabled");
                            CmdSubmit.Text = "Update";
                            div_comment.InnerHtml = "";
                        }
                        else
                        {
                            div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Type Vehicle can not be edited, due to status code has been " + sStatus + "</div>";
                        }
                        break;
                    default:
                        break;
                }

            }
            catch (Exception ex)
            {

            }
        }

