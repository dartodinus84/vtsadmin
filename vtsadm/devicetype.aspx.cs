                LblDeviceTypeID.InnerHtml = "";
                txtDeviceTypeIDDelete.Value = "";
                txtStatusDelete.Value = "";

                CmdSubmit.Text = "Submit";
            }
            catch (Exception ex)
            {

            }
        }
