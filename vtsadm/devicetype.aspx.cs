        protected void Open_GridView()
        {
            try
            {
                ClsType ClType = new ClsType();
                string strSQL = "sp_list_device_type '" + txtSearch.Text.Trim() + "'";
                ViewState[sViewStateFieldSort] = "DeviceTypeID";
                ViewState[sViewStateDirSort] = "ASC";
