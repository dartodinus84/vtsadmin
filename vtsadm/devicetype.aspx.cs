        protected void CmdYesSubmit_ServerClick(object sender, EventArgs e)
        {
            try
            {
                Int32 intAff = 0; String strSQL = "";
                ExecCommand ec = new ExecCommand();
                if (CmdSubmit.Text.ToUpper() == "SUBMIT")
                {
                    strSQL = "sp_insert_device_type '" + txtDevBrand.Text.Trim() + "','" + txtDevModel.Text.Trim() + "','" + txtDevTypeDesc.Text.Trim() + "','" + CmbDeviceGroupID.SelectedItem.Value.Trim() + "','" + Session["ClsTypeUserID"].ToString() + "'";
                    if (ec.Execute(strSQL, Session["ClsTypeDBConnStringSQL"].ToString().Trim(), ref intAff))
                    {
                        if (intAff > 0)
                        {
                            clear();
                            Open_GridView();
                            div_comment.InnerHtml = "<div class='alert alert-success' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Success!</strong> Device type has been save successfully!</div>";
                        }
                        else
                        {
                            div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Saving device type has been failed</div>";
                        }
                    }
                }
                else
                {
                    if (txtDevTypeID.Text.Trim() != "")
                    {
                        strSQL = "sp_update_device_type '" + txtDevTypeID.Text.Trim() + "','" + txtDevBrand.Text.Trim() + "','" + txtDevModel.Text.Trim() + "','" + txtDevTypeDesc.Text.Trim() + "','" + CmbDeviceGroupID.SelectedItem.Value.Trim() + "','" + Session["ClsTypeUserID"].ToString() + "'";
                        if (ec.Execute(strSQL, Session["ClsTypeDBConnStringSQL"].ToString().Trim(), ref intAff))
                        {
                            if (intAff > 0)
                            {
                                clear();
                                Open_GridView();
                                div_comment.InnerHtml = "<div class='alert alert-success' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Success!</strong> Device type has been update successfully!</div>";
                            }
                            else
                            {
                                div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Update device type has been failed</div>";
                            }
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Insert or update device type has been failed (" + ex.Message + ")</div>";
            }
        }

        protected void GridView2_RowCommand(object sender, System.Web.UI.WebControls.GridViewCommandEventArgs e)
        {
            try
            {
                Int32 iRow = Convert.ToInt32(e.CommandArgument);
                string sDevTypeID = ""; string sDevTypeDesc = ""; string sDevGroupID = ""; string sDevBrand = ""; string sDevModel = "";
                sDevTypeID = (e.CommandSource as GridView).Rows[iRow].Cells[0].Text.Trim();
                sDevBrand = (e.CommandSource as GridView).Rows[iRow].Cells[1].Text.Trim();
                sDevModel = (e.CommandSource as GridView).Rows[iRow].Cells[2].Text.Trim();
                sDevTypeDesc = (e.CommandSource as GridView).Rows[iRow].Cells[3].Text.Trim();
                sDevGroupID = (e.CommandSource as GridView).Rows[iRow].Cells[4].Text.Trim();
                switch (e.CommandName.ToUpper())
                {
                    case "CHANGES":
                        txtDevTypeID.Text = sDevTypeID;
                        txtDevBrand.Text = sDevBrand;
                        txtDevModel.Text = sDevModel;
                        txtDevTypeDesc.Text = sDevTypeDesc;
                        CmbDeviceGroupID.SelectedValue = sDevGroupID;
                        txtDevTypeID.Attributes.Add("disabled", "disabled");
                        CmdSubmit.Text = "Update";
                        div_comment.InnerHtml = "";
                        break;
                    default:
                        break;
                }

            }
            catch (Exception ex)
            {

            }
        }

