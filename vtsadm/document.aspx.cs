        protected void GridView2_RowCommand(object sender, System.Web.UI.WebControls.GridViewCommandEventArgs e)
        {
            try
            {
                Int32 iRow = Convert.ToInt32(e.CommandArgument);
                string sDocID = ""; string sDocName = ""; 
                sDocID = (e.CommandSource as GridView).Rows[iRow].Cells[0].Text.Trim();
                sDocName = (e.CommandSource as GridView).Rows[iRow].Cells[1].Text.Trim();
                switch (e.CommandName.ToUpper())
                {
                    case "CHANGES":
                        txtDocID.Text = sDocID;
                        txtDocName.Text = sDocName;
                        txtDocID.Attributes.Add("disabled", "disabled");
                        CmdSubmit.Text = "Update";
                        div_comment.InnerHtml = "";
                        break;
                    default:
                        break;
                }

            }
            catch (Exception ex)
            {
                div_comment.InnerHtml = "<div class='alert alert-danger' role='alert'><button type = 'button' class='close' data-dismiss='alert' aria-label='Close'><span aria-hidden='true'>&times;</span></button><strong>Failed!</strong> Removing document has been failed (" + ex.Message + ")</div>";
            }
        }

